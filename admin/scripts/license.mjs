// Writes src/app/core/license.generated.ts with the PrimeUI license key (empty if none).
// Key source, first match wins:
//   1. the PRIMEUI_LICENSE environment variable (Vercel / CI)
//   2. PRIMEUI_LICENSE=... in admin/.env or the repo-root .env (local dev; both are gitignored)
// The key ends up in the browser bundle by design (PrimeUI verifies it offline); it is not a server secret.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const fromEnvFile = (rel) => {
  const path = fileURLToPath(new URL(rel, import.meta.url));
  if (!existsSync(path)) return '';
  const line = readFileSync(path, 'utf8').split(/\r?\n/).find((l) => /^\s*PRIMEUI_LICENSE\s*=/.test(l));
  return line ? line.replace(/^\s*PRIMEUI_LICENSE\s*=\s*/, '').trim().replace(/^(['"])(.*)\1$/, '$2') : '';
};

const key = process.env.PRIMEUI_LICENSE || fromEnvFile('../.env') || fromEnvFile('../../.env') || '';
const out = fileURLToPath(new URL('../src/app/core/license.generated.ts', import.meta.url));
writeFileSync(out, `// GENERATED by scripts/license.mjs - do not edit or commit.\nexport const PRIMEUI_LICENSE: string = ${JSON.stringify(key)};\n`);
console.log(key ? 'PrimeUI license key found.' : 'No PrimeUI license key (PRIMEUI_LICENSE): the admin will show a license notice.');
