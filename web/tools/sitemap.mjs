#!/usr/bin/env node
/**
 * Regenerates sitemap.xml, robots.txt and manifest.webmanifest from js/site.config.js.
 *
 *   node tools/sitemap.mjs
 *
 * Products and categories are NOT in site.config.js any more: they live in the API. Pass the API
 * base URL to include them (slugs are fetched from /api/products and /api/categories):
 *
 *   API=https://geardoctor.example node tools/sitemap.mjs
 *
 * Without API=..., product and category URLs are skipped (guides, about, contact etc. still listed).
 * Re-run after the catalogue, guides or store.siteUrl change.
 * While store.siteUrl is a [PLACEHOLDER], the example.com base is used and the output says so.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { default: config } = await import(pathToFileURL(path.join(root, "js", "site.config.js")).href);

const PLACEHOLDER = /\[PLACEHOLDER/i;
const isReal = (v) => typeof v === "string" && v.trim() && !PLACEHOLDER.test(v);
const liveUrl = isReal(config.store?.siteUrl) ? config.store.siteUrl.trim().replace(/\/+$/, "") : null;
const base = liveUrl || "https://example.com";
const placeholderNote = liveUrl
  ? ""
  : "  PLACEHOLDER: store.siteUrl is not set yet, so this file uses https://example.com.\n" +
    "  Set config.store.siteUrl and re-run `node tools/sitemap.mjs` before launch.\n";
const today = new Date().toISOString().slice(0, 10);
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const apiBase = (process.env.API || "").replace(/\/+$/, "");
let productSlugs = [], categorySlugs = [];
if (apiBase) {
  try {
    const get = async (p) => { const r = await fetch(apiBase + p); if (!r.ok) throw new Error(p + " " + r.status); return r.json(); };
    categorySlugs = (await get("/api/categories")).map((c) => c.slug);
    for (let page = 1; ; page++) {
      const d = await get(`/api/products?pageSize=60&page=${page}`);
      productSlugs.push(...d.items.map((p) => p.slug));
      if (page * d.pageSize >= d.total || !d.items.length) break;
    }
  } catch (e) { console.warn("  could not read the API, skipping products/categories:", e.message); }
} else {
  console.log("  note: API env var not set, product and category URLs are skipped.");
}

const ids = (list) => (list || []).map((x) => x.id).filter((id) => isReal(id));

/** [path, priority] pairs. Home is "" so the URL ends with "/". */
const entries = [
  ["", 1.0],
  ["shop.html", 0.9],
  ...categorySlugs.map((id) => [`shop.html?cat=${encodeURIComponent(id)}`, 0.8]),
  ["gear-doctor.html", 0.8],
  ...productSlugs.map((id) => [`product.html?slug=${encodeURIComponent(id)}`, 0.7]),
  ...ids(config.guides).map((id) => [`guide.html?id=${encodeURIComponent(id)}`, 0.6]),
  ["about.html", 0.5],
  ["contact.html", 0.5],
  ["cart.html", 0.3],
];

const seen = new Set();
const urls = entries.filter(([p]) => (seen.has(p) ? false : seen.add(p)));

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/sitemap.mjs from js/site.config.js. Do not edit by hand.
${placeholderNote}-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls
  .map(
    ([p, prio]) => `  <url>
    <loc>${esc(`${base}/${p}`)}</loc>
    <lastmod>${today}</lastmod>
    <priority>${prio.toFixed(1)}</priority>
  </url>`,
  )
  .join("\n")}
</urlset>
`;

const robots = `# robots.txt: allow all crawlers.
${placeholderNote ? "# PLACEHOLDER: the Sitemap line below uses the example domain until store.siteUrl is set.\n# Re-run node tools/sitemap.mjs after setting it.\n" : ""}User-agent: *
Allow: /

Sitemap: ${base}/sitemap.xml
`;

const titleBase = String(config.seo?.defaultTitle || "").split(" — ")[0].trim() || config.store?.shortName;
const manifest = {
  name: titleBase,
  short_name: config.store?.shortName || titleBase,
  description: config.seo?.description,
  start_url: "./index.html",
  scope: "./",
  display: "standalone",
  background_color: config.theme?.colors?.bg || "#0A0A0C",
  theme_color: config.theme?.colors?.bg || "#0A0A0C",
  lang: "en",
  icons: [
    { src: "assets/img/icons/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
    { src: "assets/img/icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
    { src: "assets/img/icons/icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
  ],
};

writeFileSync(path.join(root, "sitemap.xml"), sitemap);
writeFileSync(path.join(root, "robots.txt"), robots);
writeFileSync(path.join(root, "manifest.webmanifest"), JSON.stringify(manifest, null, 2) + "\n");

console.log(`sitemap.xml: ${urls.length} URLs (base ${base})`);
console.log(`  products: ${productSlugs.length}, guides: ${ids(config.guides).length}, categories: ${categorySlugs.length}`);
