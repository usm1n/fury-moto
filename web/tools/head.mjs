// Regenerates the performance block in every page <head>. Re-run after adding/removing JS modules,
// changing the default fonts or the backdrop frame folders:
//   node tools/head.mjs
//
// It writes, between <!-- perf:start --> and <!-- perf:end -->:
//   - the default Google Fonts stylesheet (static, so text renders early; js/core/config.js swaps it
//     only if config.theme.fonts changes)
//   - a preload of the first backdrop frame, matched to orientation/size with media queries
//     (same rule as pickPath() in js/core/backdrop.js), so the background paints immediately
//   - <link rel="modulepreload"> for every JS module the page needs (static import graph of
//     js/core/app.js + the page module + the components the page mounts), so the browser fetches
//     them in parallel instead of discovering them one import level at a time
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rel = (p) => path.relative(root, p).split(path.sep).join("/");
const config = (await import(pathToFileURL(path.join(root, "js/site.config.js")).href)).default;

/* ---------- module graph ---------- */
// static imports, side-effect imports, import("…") and the pages' loadModule("…") helper
const IMPORT_RE = /(?:import|export)\s[^"'`]*?from\s*["']([^"']+)["']|import\s*["']([^"']+)["']|(?:import|loadModule)\(\s*["']([^"']+)["']/g;
function graph(entry, seen = new Set()) {
  if (seen.has(entry) || !fs.existsSync(entry)) return seen;
  seen.add(entry);
  const src = fs.readFileSync(entry, "utf8");
  for (const m of src.matchAll(IMPORT_RE)) {
    const spec = m[1] || m[2] || m[3];
    if (!spec || !spec.startsWith(".")) continue;
    graph(path.resolve(path.dirname(entry), spec), seen);
  }
  return seen;
}

/* ---------- fonts ---------- */
const SINGLE_WEIGHT = /^(Anton|Bebas Neue|Oswald Bold)$/i;
const fonts = [config.theme?.fonts?.display, config.theme?.fonts?.body].filter(Boolean);
const fontHref = "https://fonts.googleapis.com/css2?" + fonts
  .map((f) => `family=${encodeURIComponent(f).replace(/%20/g, "+")}${SINGLE_WEIGHT.test(f) ? "" : ":wght@400;500;600;700"}`)
  .join("&") + "&display=swap";

/* ---------- first backdrop frame ---------- */
const first = (p) => p && p.replace(/%0?(\d*)d/, (_, n) => "1".padStart(Number(n) || 0, "0"));
const seq = config.backdrop?.sequences || {};
// pickPath(): small set only when it covers the viewport without upscaling; in practice
// landscape screens >= ~1240 css px wide (or high-DPI) need the large set.
const framePreloads = config.backdrop?.enabled ? [
  seq.landscape?.path && [first(seq.landscape.path), "(orientation: landscape) and (min-width: 1240px), (orientation: landscape) and (min-resolution: 1.5dppx)"],
  seq.landscape?.pathSmall && [first(seq.landscape.pathSmall), "(orientation: landscape) and (max-width: 1239.98px) and (max-resolution: 1.49dppx)"],
  seq.portrait?.path && [first(seq.portrait.path), "(orientation: portrait) and (min-resolution: 1.5dppx)"],
  seq.portrait?.pathSmall && [first(seq.portrait.pathSmall), "(orientation: portrait) and (max-resolution: 1.49dppx)"],
].filter(Boolean) : [];

/* ---------- pages ---------- */
const pages = fs.readdirSync(root).filter((f) => f.endsWith(".html"));
for (const file of pages) {
  const full = path.join(root, file);
  let html = fs.readFileSync(full, "utf8").replace(/\r\n/g, "\n");
  const pageName = /boot\("([^"]+)"\)/.exec(html)?.[1];
  if (!pageName) { console.log("skip (no boot):", file); continue; }

  const entries = [path.join(root, "js/core/app.js"), path.join(root, `js/pages/${pageName}.js`)];
  for (const m of html.matchAll(/data-component="([^"]+)"/g)) entries.push(path.join(root, `js/components/${m[1]}.js`));
  const mods = new Set();
  entries.forEach((e) => graph(e, mods));
  const modLinks = [...mods].map(rel).sort((a, b) => (a.startsWith("js/core/app") ? -1 : b.startsWith("js/core/app") ? 1 : a.localeCompare(b)));

  const block = [
    "<!-- perf:start (generated by tools/head.mjs; edit that, not this) -->",
    `<link rel="stylesheet" href="${fontHref}" data-theme-fonts>`,
    ...framePreloads.map(([href, media]) => `<link rel="preload" as="image" type="image/webp" href="${href}" media="${media}" fetchpriority="high">`),
    ...modLinks.map((m) => `<link rel="modulepreload" href="${m}">`),
    "<!-- perf:end -->",
  ].map((l) => "  " + l).join("\n");

  // drop the stale hero-poster preload and any previous generated block
  html = html.replace(/\n\s*<link rel="preload" as="image" href="assets\/video\/rider-hero-poster\.webp"[^>]*>/g, "");
  html = html.replace(/\n\s*<!-- perf:start[\s\S]*?<!-- perf:end -->/g, "");
  // insert right after the gstatic preconnect
  const anchor = /(<link rel="preconnect" href="https:\/\/fonts\.gstatic\.com" crossorigin>)/;
  if (!anchor.test(html)) { console.log("skip (no preconnect anchor):", file); continue; }
  html = html.replace(anchor, `$1\n${block}`);
  fs.writeFileSync(full, html);
  console.log(`${file.padEnd(18)} page=${pageName.padEnd(12)} modules=${modLinks.length} framePreloads=${framePreloads.length}`);
}
